import assert from 'node:assert/strict';
import {sessionRows,filterSessionRows,sessionOpenAction,sessionListHtml} from '../app/ui/js/sessions-page.js';
const source={agent_id:'codex',session_id:'a'.repeat(64),thread_id:'one'};
const other={...source,session_id:'b'.repeat(64),thread_id:'two'};
const live={source,name:'Codex',target:{exactSession:true},observation:{status:'waiting'}};
const snapshot={revision:1,tasks:[{id:'task',title:'<历史任务>'}],runs:[{id:'old',task_id:'task',source:other,status:'running',started_ms:1},{id:'latest',task_id:'task',source,status:'ready',started_ms:2},{id:'local',task_id:'task',source:null,status:'running',started_ms:3},{id:'foreign',task_id:'missing',source:other,started_ms:4}]};
const rows=sessionRows([live],snapshot);
assert.equal(rows.length,2);
assert.equal(rows[0].observed,live);
assert.equal(rows[0].records[0].runId,'latest');
assert.equal(rows[1].records[0].runId,'old','history never inherits task current source');
assert.equal(sessionOpenAction(rows[1]).record.runId,'old');
assert.equal(sessionOpenAction(rows[0]).kind,'observed');
const changed={...live,source:{...source,thread_id:'conflicting'}};
assert.equal(sessionRows([changed],snapshot).length,3,'thread mismatch never merges identity');
assert.equal(sessionRows([{...live,target:null}],{tasks:[],runs:[]}).length,1);
assert.equal(sessionOpenAction({...rows[0],observed:{...live,target:null}}),null,'unavailable current source cannot fall through to history');
assert.equal(filterSessionRows(rows,{scope:'saved'}).length,1);
assert.equal(filterSessionRows(rows,{scope:'observed',query:'codex 历史'}).length,1);
assert.equal(filterSessionRows(rows,{tool:'missing'}).length,0);
const html=sessionListHtml(rows);
assert.ok(html.includes('&lt;历史任务&gt;')&&!html.includes('<历史任务>'));
assert.ok(html.includes('历史记录')&&!html.includes('执行中'),'historical running state is never current execution');
assert.ok(sessionListHtml(rows,true).includes(' disabled'));
assert.equal(sessionOpenAction({...rows[1],source:{...other,agent_id:'traework'}}).label,'打开工具');
assert.equal(sessionRows([],snapshot).find(row=>row.source.session_id===source.session_id).observed,null);
console.log('PASS: source identity, saved-run isolation, unavailable current targets, history semantics, filters and escaped output');

const {sessionPage,sessionRecordsHtml}=await import('../app/ui/js/sessions-page.js');
const many=Array.from({length:123},(_,i)=>({...rows[1],key:`source-${i}`,records:[{...rows[1].records[0],title:`任务 ${i}`}]}));
assert.equal(sessionPage(many).shown,50);
assert.equal(sessionPage(many).total,123);
assert.equal(sessionPage(many,100).more,true);
assert.equal(sessionPage(many,150).items.length,123);
assert.equal(sessionPage(many,NaN).shown,50);
assert.equal(filterSessionRows(many,{query:'任务 122'}).length,1,'search sees beyond the rendered batch');
const repeated={...rows[1],records:Array.from({length:123},(_,i)=>({taskId:`task-${i}`,runId:`run-${i}`,title:`<任务 ${i}>`,status:'running',started:i}))};
assert.equal((sessionListHtml([repeated]).match(/data-session-record-task=/g)||[]).length,0,'collapsed history creates no record controls');
const opened=sessionListHtml([repeated],false,new Map([[repeated.key,{open:true,limit:50}]]));
assert.equal((opened.match(/data-session-record-task=/g)||[]).length,50);
assert.match(opened,/更多记录 · 50\/123/);
assert.equal((sessionRecordsHtml(repeated,150).match(/data-session-record-task=/g)||[]).length,123);
assert.match(sessionRecordsHtml(repeated,150),/data-session-record-task="run-122"/);
assert.ok(!sessionRecordsHtml(repeated,150).includes('<任务'));
assert.match(sessionRecordsHtml(repeated,1,true),/disabled/);
console.log('PASS: whole-data search, progressive source/record rendering, lazy history, exact record task IDs and escaping');

const {catalogSummary}=await import('../app/ui/js/sessions-page.js');
const entry={source:{...source,session_id:'c'.repeat(64),thread_id:'019c6e27-e55b-73d1-87d8-4e01f1f75099'},name:'Codex',modified_ms:100,archived:true,target:{exactSession:true}};
const combined=sessionRows([live],snapshot,[{...entry,source},entry]);
assert.equal(combined.length,3);
assert.equal(combined.find(row=>row.observed)?.records[0].runId,'latest');
assert.equal(filterSessionRows(combined,{scope:'catalog'}).length,2);
assert.equal(filterSessionRows(combined,{scope:'saved'}).length,1,'unlinked directory rows are not saved task history');
const disk=combined.find(row=>row.source.session_id===entry.source.session_id);
assert.equal(sessionOpenAction(disk).kind,'catalog');
assert.equal(sessionOpenAction(combined.find(row=>row.observed)).kind,'observed');
assert.equal(filterSessionRows(combined,{query:entry.source.thread_id}).length,1);
assert.match(sessionListHtml([disk]),/归档会话/);
assert.match(sessionListHtml([disk]),/会话 4e01f1f75099/);
assert.match(sessionListHtml([disk],false,new Map(),true),/data-session-open=.* disabled/);
const gaps={unreadable:1,invalid:2,compressed:3,deep_directories:4,missing_roots:1};
const summary=catalogSummary({items:[entry],gaps});
assert.match(summary,/1 个可核验记录/);assert.match(summary,/2 项无法核验/);assert.match(summary,/3 项压缩记录暂不支持/);
assert.ok(!sessionListHtml([disk]).includes('执行中'));
console.log('PASS: verified directory merges, archive semantics, explicit gaps, thread search and per-directory action guards');

const noThread={agent_id:'claude',session_id:'e'.repeat(52)+'123456abcdef',thread_id:null};
const noThreadSnapshot={revision:1,tasks:[{id:'no-thread-task',title:'已保存方案'}],runs:[{id:'no-thread-run',task_id:'no-thread-task',source:noThread,status:'ready',started_ms:1}]};
const noThreadHistory=sessionRows([],noThreadSnapshot);
const noThreadObserved=sessionRows([{source:noThread,name:'Claude Code',target:{exactSession:false},observation:{status:'waiting'}}],{tasks:[],runs:[]});
assert.match(sessionListHtml(noThreadObserved),/会话 123456abcdef/);
assert.equal(filterSessionRows(noThreadObserved,{query:'123456abcdef'}).length,1,'the displayed fallback session suffix is searchable');
assert.equal(filterSessionRows(noThreadObserved,{query:noThread.session_id}).length,1,'complete fallback session IDs are searchable');
assert.equal(filterSessionRows(noThreadHistory,{query:'claude 123456abcdef 方案',scope:'saved'}).length,1,'fallback IDs compose with tool, task and scope filters');
assert.equal(filterSessionRows(noThreadHistory,{query:'123456abcdeg'}).length,0,'different source IDs never match');
assert.equal(filterSessionRows(noThreadObserved,{query:noThread.session_id,tool:'codex'}).length,0,'identifier matching cannot broaden the selected tool');
assert.equal(sessionOpenAction(noThreadObserved[0]).label,'打开工具','searching an identity does not upgrade navigation capability');
console.log('PASS: visible fallback suffix and full source ID search with existing tool/scope filters and capability boundaries');
